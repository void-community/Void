using System.Text;
using Microsoft.CodeAnalysis;

namespace Void.IntegrationTests.Generators;

public abstract class ReleaseGroupGeneratorBase : IIncrementalGenerator
{
    private const string FixturesNamespace = "global::Void.IntegrationTests.Infrastructure.Fixtures";

    /// <summary>The servers every test family runs against: Paper for vanilla clients, and the mod loaders the proxy supports.</summary>
    private static readonly ServerType[] ServerTypes =
    [
        new(Name: "Paper", FixtureTypeName: "PaperFixture", FixtureParameterName: "paperFixture", IsClassFixture: false),
        new(Name: "Forge", FixtureTypeName: "ForgeFixture", FixtureParameterName: "forgeFixture", IsClassFixture: true),
        new(Name: "NeoForge", FixtureTypeName: "NeoForgeFixture", FixtureParameterName: "neoForgeFixture", IsClassFixture: true)
    ];

    public abstract void Initialize(IncrementalGeneratorInitializationContext context);

    /// <summary>
    /// Generates a test family for every server type and release group, such as <c>PaperProxiedServerRedirectionTests_1_12</c> and
    /// <c>ForgeProxiedServerRedirectionTests_1_12</c>.
    /// </summary>
    /// <param name="familyName">The family's class name without its server type prefix and release suffix.</param>
    /// <param name="baseClassName">The test base the family's classes derive from.</param>
    /// <param name="otherFixtures">The fixtures the base takes after the server fixture, by type name in the fixtures namespace and parameter name.</param>
    /// <param name="methodNameFormat">The test method name, with <c>{0}</c> standing for the server name.</param>
    protected static string GenerateFamilySource(
        string familyName,
        string baseClassName,
        IReadOnlyList<(string TypeName, string ParameterName)> otherFixtures,
        string methodNameFormat,
        CancellationToken cancellationToken
    )
    {
        cancellationToken.ThrowIfCancellationRequested();

        var otherParameters = string.Concat(otherFixtures.Select(fixture => $", {FixturesNamespace}.{fixture.TypeName} {fixture.ParameterName}"));
        var otherArguments = string.Concat(otherFixtures.Select(fixture => $", {fixture.ParameterName}"));
        var sourceBuilder = new StringBuilder();

        sourceBuilder.AppendLine("// <auto-generated />");
        sourceBuilder.AppendLine("#nullable enable");
        sourceBuilder.AppendLine();
        sourceBuilder.AppendLine($"namespace Void.IntegrationTests.Connections.{familyName};");
        sourceBuilder.AppendLine();

        foreach (var serverType in ServerTypes)
        {
            var classFixture = serverType.IsClassFixture ? $", global::Xunit.IClassFixture<{FixturesNamespace}.{serverType.FixtureTypeName}>" : "";

            foreach (var (key, releases) in EnumerateReleaseGroups())
            {
                cancellationToken.ThrowIfCancellationRequested();

                sourceBuilder.AppendLine($"public sealed class {serverType.Name}{familyName}_{key}({FixturesNamespace}.{serverType.FixtureTypeName} {serverType.FixtureParameterName}{otherParameters}) : {baseClassName}({serverType.FixtureParameterName}{otherArguments}){classFixture}");
                sourceBuilder.AppendLine("{");

                AppendTestMethodForReleases(sourceBuilder, string.Format(methodNameFormat, serverType.Name), releases);

                sourceBuilder.AppendLine("}");
                sourceBuilder.AppendLine();
            }
        }

        return sourceBuilder.ToString();
    }

    protected static void AppendTestMethodForReleases(StringBuilder sourceBuilder, string methodName, IEnumerable<string> releases)
    {
        sourceBuilder.AppendLine("    public static global::Xunit.TheoryData<global::Void.Minecraft.Network.ProtocolVersion> ProtocolVersions { get; } =");
        sourceBuilder.AppendLine("    [");

        foreach (var release in releases)
            sourceBuilder.AppendLine($"        global::Void.Minecraft.Network.ProtocolVersion.MINECRAFT_{release},");

        sourceBuilder.AppendLine("    ];");
        sourceBuilder.AppendLine();
        sourceBuilder.AppendLine("    [global::Xunit.Theory]");
        sourceBuilder.AppendLine("    [global::Xunit.MemberData(nameof(ProtocolVersions))]");
        sourceBuilder.AppendLine($"    public async global::System.Threading.Tasks.Task {methodName}(global::Void.Minecraft.Network.ProtocolVersion protocolVersion)");
        sourceBuilder.AppendLine("    {");
        sourceBuilder.AppendLine("        await base.RunAsync(protocolVersion);");
        sourceBuilder.AppendLine("    }");
    }

    private static IEnumerable<(string Key, IEnumerable<string> Releases)> EnumerateReleaseGroups()
    {
        return ReleaseVersionGroups.MajorMinor
            .OrderBy(group => group.Key)
            .Select(pair => (Key: pair.Key.ToString().Replace('.', '_'), Releases: pair.Value.Select(release => release.ToString().Replace('.', '_'))));
    }

    private sealed record ServerType(string Name, string FixtureTypeName, string FixtureParameterName, bool IsClassFixture);
}
