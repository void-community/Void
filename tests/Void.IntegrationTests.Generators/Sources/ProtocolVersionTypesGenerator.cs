using System.Text;
using Microsoft.CodeAnalysis;

namespace Void.IntegrationTests.Generators.Sources;

[Generator(LanguageNames.CSharp)]
public sealed class ProtocolVersionTypesGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var generatedSourceProvider = context.CompilationProvider.Select(static (_, cancellationToken) => GenerateSource(cancellationToken));

        context.RegisterSourceOutput(generatedSourceProvider, static (sourceProductionContext, generatedSource) =>
        {
            if (generatedSource.Length is 0)
                return;

            sourceProductionContext.AddSource("ProtocolVersionTypes.g.cs", generatedSource);
        });
    }

    private static string GenerateSource(CancellationToken cancellationToken)
    {
        var sourceBuilder = new StringBuilder();

        sourceBuilder.AppendLine("// <auto-generated />");
        sourceBuilder.AppendLine("#nullable enable");
        sourceBuilder.AppendLine();
        sourceBuilder.AppendLine($"namespace {ProtocolVersionTypes.Namespace};");
        sourceBuilder.AppendLine();

        foreach (var key in ProtocolVersionTypes.Keys)
        {
            cancellationToken.ThrowIfCancellationRequested();

            sourceBuilder.AppendLine($"public sealed class Minecraft_{key} : global::Void.IntegrationTests.Infrastructure.Harness.IProtocolVersionType");
            sourceBuilder.AppendLine("{");
            sourceBuilder.AppendLine($"    public static global::Void.Minecraft.Network.ProtocolVersion ProtocolVersion => global::Void.Minecraft.Network.ProtocolVersion.MINECRAFT_{key};");
            sourceBuilder.AppendLine("}");
            sourceBuilder.AppendLine();
        }

        return sourceBuilder.ToString();
    }
}
