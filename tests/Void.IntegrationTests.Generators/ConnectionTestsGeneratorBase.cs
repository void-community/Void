using System.Text;
using Microsoft.CodeAnalysis;

namespace Void.IntegrationTests.Generators;

public abstract class ConnectionTestsGeneratorBase : IIncrementalGenerator
{
    private const string FixturesNamespace = "global::Void.IntegrationTests.Infrastructure.Fixtures";

    /// <summary>
    /// The servers every test family runs against: Paper for vanilla clients, and the mod loaders the proxy supports. Each has a fixture
    /// with one server and one with a pair, which both start the proxy in front of them.
    /// </summary>
    private static readonly ServerType[] ServerTypes =
    [
        new(Name: "Paper", FixtureTypeName: "VoidFixture", PairFixtureTypeName: "VoidFixture"),
        new(Name: "Forge", FixtureTypeName: "ForgeFixture", PairFixtureTypeName: "ForgePairFixture"),
        new(Name: "NeoForge", FixtureTypeName: "NeoForgeFixture", PairFixtureTypeName: "NeoForgePairFixture")
    ];

    public abstract void Initialize(IncrementalGeneratorInitializationContext context);

    /// <summary>
    /// Generates a test class for every server type and protocol version, such as <c>PaperProxiedServerRedirectionTests_1_12_1</c> and
    /// <c>ForgeProxiedServerRedirectionTests_1_12_1</c>, whose fixtures start everything the test plays on before it runs.
    /// </summary>
    /// <param name="familyName">The family's class name without its server type prefix and protocol version suffix.</param>
    /// <param name="baseClassName">The test base the family's classes derive from.</param>
    /// <param name="clientFixture">The client fixture the base takes after the servers fixture, by type name in the fixtures namespace and parameter name.</param>
    /// <param name="serverPair">Whether the family plays on two servers.</param>
    /// <param name="methodNameFormat">The test method name, with <c>{0}</c> standing for the server type.</param>
    protected static string GenerateFamilySource(
        string familyName,
        string baseClassName,
        (string TypeName, string ParameterName) clientFixture,
        bool serverPair,
        string methodNameFormat,
        CancellationToken cancellationToken
    )
    {
        cancellationToken.ThrowIfCancellationRequested();

        var sourceBuilder = new StringBuilder();

        sourceBuilder.AppendLine("// <auto-generated />");
        sourceBuilder.AppendLine("#nullable enable");
        sourceBuilder.AppendLine();
        sourceBuilder.AppendLine($"namespace Void.IntegrationTests.Connections.{familyName};");
        sourceBuilder.AppendLine();

        foreach (var serverType in ServerTypes)
        {
            var methodName = string.Format(methodNameFormat, serverType.Name);

            foreach (var key in ProtocolVersionTypes.Keys)
            {
                cancellationToken.ThrowIfCancellationRequested();

                var serversFixture = $"{FixturesNamespace}.{(serverPair ? serverType.PairFixtureTypeName : serverType.FixtureTypeName)}<{ProtocolVersionTypes.TypeName(key)}>";

                sourceBuilder.AppendLine($"public sealed class {serverType.Name}{familyName}_{key}({serversFixture} serversFixture, {FixturesNamespace}.{clientFixture.TypeName} {clientFixture.ParameterName}) : {baseClassName}(serversFixture, {clientFixture.ParameterName}), global::Xunit.IClassFixture<{serversFixture}>");
                sourceBuilder.AppendLine("{");
                sourceBuilder.AppendLine("    [global::Xunit.Fact]");
                sourceBuilder.AppendLine($"    public async global::System.Threading.Tasks.Task {methodName}()");
                sourceBuilder.AppendLine("    {");
                sourceBuilder.AppendLine("        await base.RunAsync();");
                sourceBuilder.AppendLine("    }");
                sourceBuilder.AppendLine("}");
                sourceBuilder.AppendLine();
            }
        }

        return sourceBuilder.ToString();
    }

    private sealed record ServerType(string Name, string FixtureTypeName, string PairFixtureTypeName);
}
