using System.Text;
using Microsoft.CodeAnalysis;

namespace Void.IntegrationTests.Generators;

public abstract class ConnectionTestsGeneratorBase : IIncrementalGenerator
{
    public abstract void Initialize(IncrementalGeneratorInitializationContext context);

    /// <summary>
    /// Generates a test class for every server type and protocol version, such as <c>PaperProxiedServerRedirectionTests_1_12_1</c> and
    /// <c>ForgeProxiedServerRedirectionTests_1_12_1</c>, in the collection whose fixture holds the servers it plays on.
    /// </summary>
    /// <param name="familyName">The family's class name without its server type prefix and protocol version suffix.</param>
    /// <param name="baseClassName">The test base the family's classes derive from.</param>
    /// <param name="clientFixture">The client fixture the base takes last, by type name in the fixtures namespace and parameter name.</param>
    /// <param name="serverPair">Whether the family plays on two servers.</param>
    /// <param name="proxied">Whether the family plays through the proxy, which its classes start in front of the collection's servers.</param>
    /// <param name="methodNameFormat">The test method name, with <c>{0}</c> standing for the server type.</param>
    protected static string GenerateFamilySource(
        string familyName,
        string baseClassName,
        (string TypeName, string ParameterName) clientFixture,
        bool serverPair,
        bool proxied,
        string methodNameFormat,
        CancellationToken cancellationToken
    )
    {
        cancellationToken.ThrowIfCancellationRequested();

        var sourceBuilder = new StringBuilder();
        var clientFixtureTypeName = $"{ServerCollections.FixturesNamespace}.{clientFixture.TypeName}";

        sourceBuilder.AppendLine("// <auto-generated />");
        sourceBuilder.AppendLine("#nullable enable");
        sourceBuilder.AppendLine();
        sourceBuilder.AppendLine($"namespace Void.IntegrationTests.Connections.{familyName};");
        sourceBuilder.AppendLine();

        foreach (var serverType in ServerCollections.ServerTypes)
        {
            var methodName = string.Format(methodNameFormat, serverType.Name);

            foreach (var key in ProtocolVersionKeys.All)
            {
                cancellationToken.ThrowIfCancellationRequested();

                var className = $"{serverType.Name}{familyName}_{key}";
                var protocolVersion = $"global::Void.Minecraft.Network.ProtocolVersion.MINECRAFT_{key}";
                var serversFixture = ServerCollections.FixtureTypeName(serverType, key, serverPair);
                var voidFixture = $"{ServerCollections.FixturesNamespace}.VoidFixture<{serversFixture}>";

                sourceBuilder.AppendLine($"[global::Xunit.Collection(typeof({ServerCollections.CollectionTypeName(serverType, key, serverPair)}))]");
                sourceBuilder.AppendLine(proxied
                    ? $"public sealed class {className}({serversFixture} serversFixture, {voidFixture} voidFixture, {clientFixtureTypeName} {clientFixture.ParameterName}) : {baseClassName}({protocolVersion}, serversFixture, voidFixture, {clientFixture.ParameterName}), global::Xunit.IClassFixture<{voidFixture}>"
                    : $"public sealed class {className}({serversFixture} serversFixture, {clientFixtureTypeName} {clientFixture.ParameterName}) : {baseClassName}({protocolVersion}, serversFixture, {clientFixture.ParameterName})");
                sourceBuilder.AppendLine("{");
                sourceBuilder.AppendLine("    [global::Xunit.Fact]");
                sourceBuilder.AppendLine($"    public async global::System.Threading.Tasks.Task {methodName}()");
                sourceBuilder.AppendLine("    {");
                sourceBuilder.AppendLine("        await base.RunAsync();");
                sourceBuilder.AppendLine("    }");
                sourceBuilder.AppendLine("}");
                sourceBuilder.AppendLine();
            }
        }

        return sourceBuilder.ToString();
    }
}
